import assert from 'node:assert/strict';
import { execFileSync, spawn } from 'node:child_process';
const url = process.env.MILL_TEST_DATABASE_URL;
if (!url) throw new Error('Set MILL_TEST_DATABASE_URL to a disposable local mill_test database.');
const parsed = new URL(url);
if (!['127.0.0.1','localhost'].includes(parsed.hostname) || !parsed.pathname.startsWith('/mill_test')) throw new Error('Only local mill_test databases are allowed.');
const bin = process.env.PSQL_BIN || 'psql';
const args = [url,'-X','-q','-t','-A','-v','ON_ERROR_STOP=1'];
const sync = sql => execFileSync(bin,args,{input:sql,encoding:'utf8',windowsHide:true}).trim();
const run = sql => new Promise((resolve,reject) => {
  const child=spawn(bin,args,{windowsHide:true});let out='',err='';
  child.on('error',reject);child.stdout.on('data',data=>out+=data);child.stderr.on('data',data=>err+=data);
  child.on('close',code=>resolve({code,out:out.trim(),err}));child.stdin.end(sql);
});
const auth="set role authenticated; set request.jwt.claim.sub='11111111-1111-4111-8111-111111111111';";
sync("insert into public.mill_staff values ('11111111-1111-4111-8111-111111111111',true) on conflict do nothing;");
const supplier=sync(`${auth} select public.mill_post('party','{"kind":"supplier","name":"Process race supplier"}',gen_random_uuid());`);
const customer=sync(`${auth} select public.mill_post('party','{"kind":"customer","name":"Process race customer"}',gen_random_uuid());`);
sync(`${auth} select public.mill_post('purchase','{"party_id":"${supplier}","date":"2026-09-20","raw_type_id":3,"weight":200,"unit_price":50}',gen_random_uuid());`);
const start=`begin; ${auth} select public.mill_post('processing_start','{"date":"2026-09-20","raw_type_id":3,"input_weight":150}',gen_random_uuid()); select pg_sleep(0.2); commit;`;
let results=await Promise.all([run(start),run(start)]);
assert.equal(results.filter(r=>r.code===0).length,1,'Only one start can reserve 150 of 200 kg');
const process=sync(`${auth} select b.entry_id from public.mill_batches b join public.mill_entries e on e.id=b.entry_id where b.raw_type_id=3 and b.status='ongoing' and e.voided_at is null;`);
const payload=JSON.stringify({id:process,date:'2026-09-21',outputs:[{product_id:31,weight:140,bag_size:20,bag_mark:'Talha'},{product_id:32,weight:0},{product_id:33,weight:0},{product_id:34,weight:0}]});
const complete=`begin; ${auth} select public.mill_post('processing_complete','${payload}',gen_random_uuid()); select pg_sleep(0.2); commit;`;
results=await Promise.all([run(complete),run(complete)]);
assert.equal(results.filter(r=>r.code===0).length,1,'A process completes only once under competing requests');
const sale=`begin; ${auth} select public.mill_post('sale','{"date":"2026-09-21","party_id":"${customer}","product_id":31,"weight":100,"unit_price":10,"bag_size":20,"bag_mark":"Talha"}',gen_random_uuid()); select pg_sleep(0.2); commit;`;
results=await Promise.all([run(sale),run(sale)]);
assert.equal(results.filter(r=>r.code===0).length,1,'Only one sale can consume this package variant');
assert.equal(Number(sync(`${auth} select available from public.mill_packaged_stock where product_id=31 and bag_size=20 and bag_mark='Talha';`)),40);
console.log('PASS: competing process reservations, completions, and packaged sales.');
